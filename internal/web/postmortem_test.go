// postmortemJSON calls POST /api/seances/{id}/postmortem as a JSON client.
func postmortemJSON(t *testing.T, srv *Server, id string) postmortemReply {
	t.Helper()
	rec := send(t, srv, http.MethodPost, "/api/seances/"+id+"/postmortem", "", "",
		map[string]string{"Accept": "application/json"})
	if rec.Code != http.StatusOK {
		t.Fatalf("postmortem: status = %d, body %s", rec.Code, rec.Body)
	}
	var reply postmortemReply
	decodeJSON(t, rec.Body.Bytes(), &reply)
	return reply
}

// downloadOf calls GET /api/seances/{id}/postmortem.md.
func downloadOf(t *testing.T, srv *Server, id string) *http.Response {
	t.Helper()
	rec := send(t, srv, http.MethodGet, "/api/seances/"+id+"/postmortem.md", "", "", nil)
	if rec.Code != http.StatusOK {
		t.Fatalf("download: status = %d, body %s", rec.Code, rec.Body)
	}
	return rec.Result()
}

var postmortemHeadings = []string{
	"## Summary", "## Timeline", "## Root Cause", "## Evidence",
	"## Impact", "## Remediation", "## Action Items",
}

func TestPostmortemJSONIsLLM(t *testing.T) {
	srv := newSeanceServer(t, llm.Limits{})
	res := createSeance(t, srv, crashNS, crashPod)
	streamOnce(t, srv, res.ID)

	reply := postmortemJSON(t, srv, res.ID)
	if reply.Mode != "llm" || reply.Reason != "" {
		t.Errorf("mode = %q reason = %q, want llm and empty reason", reply.Mode, reply.Reason)
	}
	if !strings.HasPrefix(reply.Markdown, "# ") {
		t.Errorf("markdown does not start with a title: %q", reply.Markdown[:min(40, len(reply.Markdown))])
	}
	if !strings.Contains(reply.Markdown, "Generated by: llm") {
		t.Error("markdown lacks \"Generated by: llm\"")
	}
	for _, h := range postmortemHeadings {
		if !strings.Contains(reply.Markdown, h) {
			t.Errorf("markdown lacks heading %q", h)
		}
	}
	if want := "/api/seances/" + res.ID + "/postmortem.md"; reply.DownloadURL != want {
		t.Errorf("downloadUrl = %q, want %q", reply.DownloadURL, want)
	}
}

func TestDownloadMatchesPostmortem(t *testing.T) {
	srv := newSeanceServer(t, llm.Limits{})
	res := createSeance(t, srv, crashNS, crashPod)
	streamOnce(t, srv, res.ID)
	reply := postmortemJSON(t, srv, res.ID)

	resp := downloadOf(t, srv, res.ID)
	body := readAll(t, resp)
	if string(body) != reply.Markdown {
		t.Error("download body differs from the postmortem markdown")
	}
	if ct := resp.Header.Get("Content-Type"); ct != "text/markdown; charset=utf-8" {
		t.Errorf("Content-Type = %q", ct)
	}
	want := regexp.MustCompile(`^attachment; filename="postmortem-` + regexp.QuoteMeta(crashPod) + `-\d{8}\.md"$`)
	if cd := resp.Header.Get("Content-Disposition"); !want.MatchString(cd) {
		t.Errorf("Content-Disposition = %q", cd)
	}
}

