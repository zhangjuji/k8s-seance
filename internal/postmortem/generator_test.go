// validBlocks is a well-formed model reply in the required format.
const validBlocks = `### SUMMARY
The container was killed by the OOM killer [E1].
### ROOT_CAUSE
Memory use exceeded the limit [E1][E2].
### REMEDIATION
- Raise the memory limit.
### ACTION_ITEMS
- [ ] Raise the memory limit. [E2]
- [ ] Profile the workload.
- [ ] Add a memory alert.
`

// validProvider returns validBlocks.
func validProvider(t *testing.T) llm.Provider {
	t.Helper()
	return &recordingProvider{text: validBlocks}
}

// recordingProvider is a fake llm.Provider. It records the last request and
// replies with text, or with err when err is set.
type recordingProvider struct {
	text  string
	err   error
	calls int
	req   llm.ChatRequest
}

func (p *recordingProvider) Stream(_ context.Context, req llm.ChatRequest, onDelta func(string) error) (llm.Usage, error) {
	p.calls++
	p.req = req
	if p.err != nil {
		return llm.Usage{}, p.err
	}
	if err := onDelta(p.text); err != nil {
		return llm.Usage{}, err
	}
	return llm.Usage{}, nil
}

// firstSentence is the expected first sentence of a spirit line, for short lines
// that the generator does not need to truncate.
func expectedFirstSentence(s string) string {
	var out []rune
	for _, r := range inline(s) {
		out = append(out, r)
		if strings.ContainsRune("。！？!?.", r) {
			break
		}
	}
	return strings.TrimSpace(string(out))
}
