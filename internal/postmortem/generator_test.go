func spiritLine(t *testing.T, turns []spirit.Turn) string {
	t.Helper()
	for i := len(turns) - 1; i >= 0; i-- {
		if turns[i].Role == "spirit" && turns[i].Content != llm.ExhaustedLine {
			return turns[i].Content
		}
	}
	t.Fatal("no spirit line in transcript")
	return ""
}

