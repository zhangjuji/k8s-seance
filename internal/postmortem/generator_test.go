func TestGenerateErrors(t *testing.T) {
	c := loadCases(t)[0]
	base := Input{Autopsy: c.a, Class: c.cls, Evidence: c.ev, Transcript: c.turns}

	t.Run("nil autopsy", func(t *testing.T) {
		_, err := Generate(context.Background(), Input{Class: c.cls}, validProvider(t))
		if err == nil {
			t.Fatal("want error for nil autopsy")
		}
	})
	t.Run("nil provider falls back", func(t *testing.T) {
		res, err := Generate(context.Background(), base, nil)
		if err != nil {
			t.Fatalf("Generate: %v", err)
		}
		if res.Mode != ModeTemplate || res.Reason != ReasonLLMError {
			t.Errorf("Mode/Reason = %q/%q, want template/llm_error", res.Mode, res.Reason)
		}
	})
	t.Run("provider error falls back", func(t *testing.T) {
		res, err := Generate(context.Background(), base, &recordingProvider{err: errors.New("upstream down")})
		if err != nil {
			t.Fatalf("Generate: %v", err)
		}
		if res.Mode != ModeTemplate || res.Reason != ReasonLLMError {
			t.Errorf("Mode/Reason = %q/%q, want template/llm_error", res.Mode, res.Reason)
		}
	})
	t.Run("budget exhausted by the provider falls back", func(t *testing.T) {
		sess := spirit.NewSession("tiny", c.a, c.cls, c.ev, llm.MockProvider{}, llm.Limits{MaxCalls: 1}, nil, "mock")
		if _, err := sess.Opening(context.Background(), nil); err != nil {
			t.Fatalf("Opening: %v", err)
		}
		res, err := Generate(context.Background(), base, sess.Provider())
		if err != nil {
			t.Fatalf("Generate: %v", err)
		}
		if res.Reason != ReasonBudgetExhausted {
			t.Errorf("Reason = %q, want %q", res.Reason, ReasonBudgetExhausted)
		}
	})
	t.Run("malformed output falls back", func(t *testing.T) {
		for name, text := range malformedOutputs() {
			res, err := Generate(context.Background(), base, &recordingProvider{text: text})
			if err != nil {
				t.Errorf("%s: Generate: %v", name, err)
				continue
			}
			if res.Mode != ModeTemplate || res.Reason != ReasonMalformed {
				t.Errorf("%s: Mode/Reason = %q/%q, want template/malformed", name, res.Mode, res.Reason)
			}
		}
	})
	t.Run("cancelled context is an error", func(t *testing.T) {
		ctx, cancel := context.WithCancel(context.Background())
		cancel()
		rec := &recordingProvider{text: validBlocks}
		_, err := Generate(ctx, base, rec)
		if !errors.Is(err, context.Canceled) {
			t.Fatalf("err = %v, want context.Canceled", err)
		}
		if rec.calls != 0 {
			t.Errorf("provider called %d times after cancel, want 0", rec.calls)
		}
	})
	t.Run("context cancelled during the call is an error", func(t *testing.T) {
		ctx, cancel := context.WithCancel(context.Background())
		defer cancel()
		_, err := Generate(ctx, base, cancelingProvider{cancel: cancel})
		if !errors.Is(err, context.Canceled) {
			t.Fatalf("err = %v, want context.Canceled", err)
		}
	})
}

// cancelingProvider cancels ctx and then fails, as a provider does when the caller gives up.
type cancelingProvider struct{ cancel context.CancelFunc }

func (p cancelingProvider) Stream(context.Context, llm.ChatRequest, func(string) error) (llm.Usage, error) {
	p.cancel()
	return llm.Usage{}, errors.New("aborted")
}

// TestGenerateBudgetExhaustedSkipsProvider checks that an exhausted budget is seen
// before any call, so the inner provider is not called again.
