// wantSections is the required order of the level-2 headings.
var wantSections = []string{"Summary", "Timeline", "Root Cause", "Evidence", "Impact", "Remediation", "Action Items"}

var (
	timelineLineRE = regexp.MustCompile(`^- \d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} UTC: `)
	evidenceLineRE = regexp.MustCompile(`^- \*\*\[(E\d+)\]\*\* \((\w+)\) `)
)

// fixtureCase is one recorded Pod with its classification and evidence.
type fixtureCase struct {
	a     *autopsy.PodAutopsy
	cls   autopsy.Classification
	ev    []autopsy.Evidence
	sess  *spirit.Session
	turns []spirit.Turn
}

// loadCases builds a short séance for each fixture: an opening and one follow-up,
// both answered by MockProvider.
func loadCases(t *testing.T) []fixtureCase {
	t.Helper()
	pods, err := fixtures.Load()
	if err != nil {
		t.Fatalf("fixtures.Load: %v", err)
	}
	out := make([]fixtureCase, 0, len(pods))
	for _, a := range pods {
		ev, err := autopsy.BuildEvidence(a, autopsy.EvidenceOptions{})
		if err != nil {
			t.Fatalf("BuildEvidence(%s): %v", a.Name, err)
		}
		cls := autopsy.Classify(a)
		sess := spirit.NewSession("test-"+a.Name, a, cls, ev, llm.MockProvider{}, llm.DefaultLimits(), nil, "mock")
		if _, err := sess.Opening(context.Background(), nil); err != nil {
			t.Fatalf("Opening(%s): %v", a.Name, err)
		}
		if _, err := sess.Ask(context.Background(), "What is the cause?", nil); err != nil {
			t.Fatalf("Ask(%s): %v", a.Name, err)
		}
		out = append(out, fixtureCase{a: a, cls: cls, ev: ev, sess: sess, turns: sess.Transcript()})
	}
	return out
}

// generateCase runs Generate for one fixture through the séance provider.
func generateCase(t *testing.T, c fixtureCase) Result {
	t.Helper()
	res, err := Generate(context.Background(), Input{
		Autopsy:    c.a,
		Class:      c.cls,
		Evidence:   c.ev,
		Transcript: c.turns,
	}, c.sess.Provider())
	if err != nil {
		t.Fatalf("Generate(%s): %v", c.a.Name, err)
	}
	return res
}

// splitSections returns the text under each "## " heading, keyed by the heading name.
func splitSections(md string) ([]string, map[string]string) {
	var order []string
	body := make(map[string]string)
	current := ""
	var sb strings.Builder
	flush := func() {
		if current != "" {
			body[current] = sb.String()
		}
		sb.Reset()
	}
	for _, line := range strings.Split(md, "\n") {
		if name, ok := strings.CutPrefix(line, "## "); ok {
			flush()
			current = name
			order = append(order, name)
			continue
		}
		if current != "" {
			sb.WriteString(line + "\n")
		}
	}
	flush()
	return order, body
}

func TestGenerateSectionsInOrder(t *testing.T) {
	for _, c := range loadCases(t) {
		t.Run(c.a.Name, func(t *testing.T) {
			res := generateCase(t, c)
			order, _ := splitSections(res.Markdown)
			if strings.Join(order, "|") != strings.Join(wantSections, "|") {
				t.Errorf("sections = %q, want %q", order, wantSections)
			}
			count := 0
			for _, line := range strings.Split(res.Markdown, "\n") {
				if strings.HasPrefix(line, "## ") {
					count++
				}
			}
			if count != 7 {
				t.Errorf("found %d \"## \" headings, want 7", count)
			}
			if !strings.HasPrefix(res.Markdown, "# Postmortem: "+c.a.Namespace+"/"+c.a.Name+"\n") {
				t.Errorf("missing title line, got:\n%s", res.Markdown)
			}
			if !strings.Contains(res.Markdown, "\n> Last words: \"") {
				t.Errorf("missing \"> Last words:\" quote line")
			}
			if res.Mode != ModeLLM || res.Reason != "" {
				t.Errorf("Mode/Reason = %q/%q, want llm/empty", res.Mode, res.Reason)
			}
			if !strings.Contains(res.Markdown, "- Generated by: llm\n") {
				t.Errorf("metadata does not say generated by llm")
			}
		})
	}
}

func TestTimelineLines(t *testing.T) {
	for _, c := range loadCases(t) {
		t.Run(c.a.Name, func(t *testing.T) {
			res := generateCase(t, c)
			_, body := splitSections(res.Markdown)
			var lines []string
			for _, line := range strings.Split(body["Timeline"], "\n") {
				if strings.HasPrefix(line, "- ") {
					lines = append(lines, line)
				}
			}
			if len(lines) == 0 {
				t.Fatalf("timeline has no entries:\n%s", body["Timeline"])
			}
			for _, line := range lines {
				if !timelineLineRE.MatchString(line) {
					t.Errorf("timeline line %q does not start with a UTC timestamp", line)
				}
			}
			// Every container state with a FinishedAt must appear as a finished entry.
			for _, ca := range c.a.Containers {
				states := []autopsy.ContainerState{ca.State}
				if ca.LastState != nil {
					states = append(states, *ca.LastState)
				}
				for _, s := range states {
					if s.FinishedAt == nil {
						continue
					}
					want := spirit.FormatDeathTime(*s.FinishedAt) + ": container " + ca.Name + ":"
					if !anyLineHas(lines, want, "finished") {
						t.Errorf("no finished entry %q in timeline:\n%s", want, body["Timeline"])
					}
				}
			}
		})
	}
}

func anyLineHas(lines []string, parts ...string) bool {
	for _, l := range lines {
		ok := true
		for _, p := range parts {
			if !strings.Contains(l, p) {
				ok = false
				break
			}
		}
		if ok {
			return true
		}
	}
	return false
}

