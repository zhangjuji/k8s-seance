// mustDeath returns the time of death of a, failing the test when it is unknown.
func mustDeath(t *testing.T, a *autopsy.PodAutopsy) time.Time {
	t.Helper()
	d, ok := spirit.DeathTime(a)
	if !ok {
		t.Fatalf("no death time for %s", a.Name)
	}
	return d
}

