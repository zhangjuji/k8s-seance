func TestGenerateErrors(t *testing.T) {
	c := loadCases(t)[0]
	base := Input{Autopsy: c.a, Class: c.cls, Evidence: c.ev, Transcript: c.turns}

	t.Run("nil autopsy", func(t *testing.T) {
		_, err := Generate(context.Background(), Input{Class: c.cls}, validProvider(t))
		if err == nil {
			t.Fatal("want error for nil autopsy")
		}
	})
	t.Run("nil provider", func(t *testing.T) {
		_, err := Generate(context.Background(), base, nil)
		if err == nil {
			t.Fatal("want error for nil provider")
		}
	})
	t.Run("provider error", func(t *testing.T) {
		_, err := Generate(context.Background(), base, &recordingProvider{err: errors.New("upstream down")})
		if err == nil || !strings.Contains(err.Error(), "upstream down") {
			t.Fatalf("err = %v, want the provider error", err)
		}
	})
	t.Run("budget exhausted", func(t *testing.T) {
		sess := spirit.NewSession("tiny", c.a, c.cls, c.ev, llm.MockProvider{}, llm.Limits{MaxCalls: 1}, nil, "mock")
		if _, err := sess.Opening(context.Background(), nil); err != nil {
			t.Fatalf("Opening: %v", err)
		}
		_, err := Generate(context.Background(), base, sess.Provider())
		if !errors.Is(err, llm.ErrBudgetExhausted) {
			t.Fatalf("err = %v, want ErrBudgetExhausted", err)
		}
	})
	t.Run("malformed output", func(t *testing.T) {
		for name, text := range malformedOutputs() {
			_, err := Generate(context.Background(), base, &recordingProvider{text: text})
			if err == nil {
				t.Errorf("%s: want error, got none", name)
			}
		}
	})
}

// malformedOutputs are model replies that must be rejected.
func malformedOutputs() map[string]string {
	full := validBlocks
	noActions := strings.Split(full, "### ACTION_ITEMS")[0]
	return map[string]string{
		"missing action items": noActions,
		"duplicate header":     full + "\n### SUMMARY\nagain [E1]\n",
		"empty summary":        "### SUMMARY\n\n### ROOT_CAUSE\nx [E1]\n### REMEDIATION\ny\n### ACTION_ITEMS\n- [ ] z\n",
		"no headers at all":    "The root cause is memory [E1].",
		"empty output":         "",
	}
}

